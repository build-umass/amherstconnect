/**
 * Canonical, provider-neutral event contract.
 *
 * This module mirrors the deployed Supabase event foundation while keeping
 * provider payloads and UI-formatted values outside the canonical model.
 * Dates are UTC ISO-8601 instants; `timezone` is the IANA zone used for display.
 */

export const EVENT_SOURCE_TYPES = ['localist', 'campus_pulse', 'amherst_connect'] as const;
export const EVENT_STATUSES = ['draft', 'published', 'cancelled', 'postponed', 'archived'] as const;
export const OCCURRENCE_STATUSES = ['scheduled', 'cancelled', 'postponed'] as const;
export const EVENT_VISIBILITIES = ['public', 'authenticated', 'private'] as const;
export const REGISTRATION_TYPES = ['none', 'internal', 'external'] as const;
export const LOCATION_TYPES = ['physical', 'virtual', 'hybrid'] as const;

export type EventSourceType = (typeof EVENT_SOURCE_TYPES)[number];
export type ExternalEventSourceType = Exclude<EventSourceType, 'amherst_connect'>;
export type EventStatus = (typeof EVENT_STATUSES)[number];
export type OccurrenceStatus = (typeof OCCURRENCE_STATUSES)[number];
export type EventVisibility = (typeof EVENT_VISIBILITIES)[number];
export type RegistrationType = (typeof REGISTRATION_TYPES)[number];
export type LocationType = (typeof LOCATION_TYPES)[number];

/** UUID generated by PostgreSQL/Supabase. */
export type CanonicalId = string;
/** A timestamp representing an instant, serialized with a trailing `Z`. */
export type UtcIsoTimestamp = string;
/** An IANA zone such as `America/New_York`, never an abbreviation such as EST. */
export type IanaTimeZone = string;

export interface Coordinates {
  latitude: number;
  longitude: number;
}

export interface SourceIdentity {
  sourceType: EventSourceType;
  /** Required for imported sources; nullable only for Amherst Connect records. */
  externalId: string | null;
}

export interface SourceMetadata extends SourceIdentity {
  sourceUrl: string | null;
  sourceUpdatedAt: UtcIsoTimestamp | null;
}

