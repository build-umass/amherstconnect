/** One conceptual event, independent of how many times it occurs. */
export interface CanonicalEventRecord {
  id: CanonicalId;
  title: string;
  /** Plain text only. Provider HTML must be normalized before persistence. */
  description: string | null;
  imageUrl: string | null;
  organizationId: CanonicalId | null;
  primaryCategoryId: CanonicalId;
  status: EventStatus;
  visibility: EventVisibility;
  timezone: IanaTimeZone;
  registrationType: RegistrationType;
  registrationUrl: string | null;
  isFree: boolean;
  featuredRank: number | null;
  source: SourceMetadata;
  createdBy: CanonicalId | null;
  updatedBy: CanonicalId | null;
  createdAt: UtcIsoTimestamp;
  updatedAt: UtcIsoTimestamp;
}

/** One scheduled instance of an event, including its time and location. */
export interface CanonicalEventOccurrenceRecord {
  id: CanonicalId;
  eventId: CanonicalId;
  venueId: CanonicalId | null;
  startsAt: UtcIsoTimestamp;
  endsAt: UtcIsoTimestamp | null;
  allDay: boolean;
  status: OccurrenceStatus;
  locationType: LocationType;
  locationName: string | null;
  coordinates: Coordinates | null;
  virtualUrl: string | null;
  sourceAttendanceCount: number | null;
  source: Omit<SourceMetadata, 'sourceUrl'>;
  createdAt: UtcIsoTimestamp;
  updatedAt: UtcIsoTimestamp;
}

/** Repository output for Home, Search, Details, Map, bookmarks and RSVPs. */
export interface CanonicalEvent {
  event: CanonicalEventRecord;
  organization: CanonicalOrganization | null;
  primaryCategory: CanonicalCategory;
  categories: CanonicalCategory[];
  occurrences: Array<CanonicalEventOccurrenceRecord & { venue: CanonicalVenue | null }>;
}

